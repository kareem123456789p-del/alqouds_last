#!/usr/bin/env node
/**
 * Static route inventory generator.
 *
 * Parses app.js + routes/*.js without booting Express or touching the database.
 * Output: Markdown to stdout (redirect into qa/ROUTE_INVENTORY.md).
 *
 * Usage: node scripts/gen_route_inventory.js > qa/ROUTE_INVENTORY.md
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const appSrc = fs.readFileSync(path.join(ROOT, 'app.js'), 'utf8');

// ── Mount points: app.use('/api/x', routesVar) ──────────────────────────────
const mounts = new Map(); // routesVar -> mountPath
for (const m of appSrc.matchAll(/app\.use\(\s*['"]([^'"]+)['"]\s*,\s*(\w+)\s*\)/g)) {
  mounts.set(m[2], m[1]);
}

// Direct app-level routes (e.g. /api/customers/debt)
const directRoutes = [];
for (const m of appSrc.matchAll(/app\.(get|post|put|patch|delete)\(\s*(\[[^\]]*\]|'[^']*'|"[^"]*")\s*,\s*([^;]+)\)/g)) {
  const method = m[1].toUpperCase();
  const paths = [...m[2].matchAll(/['"]([^'"]+)['"]/g)].map(x => x[1]);
  const rest = m[3];
  const perm = (rest.match(/checkPermission\(\s*['"]([^'"]+)['"]\s*\)/) || [])[1] || null;
  const admin = /requireAdmin/.test(rest);
  for (const p of paths) directRoutes.push({ method, path: p, perm, admin, source: 'app.js' });
}

// ── Route files ─────────────────────────────────────────────────────────────
function parseRouteFile(file) {
  const src = fs.readFileSync(file, 'utf8');
  const out = [];
  const lines = src.split(/\r?\n/);
  let routerVar = 'router';
  const vm = src.match(/const\s+(\w+)\s*=\s*express\.Router\(\)/);
  if (vm) routerVar = vm[1];

  // Router-level middleware: router.use(requireAdmin) / router.use(checkPermission('x'))
  const routerPerm = (src.match(new RegExp(`\\b${routerVar}\\.use\\(\\s*checkPermission\\(\\s*['"]([^'"]+)['"]\\s*\\)`)) || [])[1] || null;
  const routerAdmin = new RegExp(`\\b${routerVar}\\.use\\(\\s*requireAdmin\\s*\\)`).test(src);

  const re = new RegExp(`\\b${routerVar}\\.(get|post|put|patch|delete|all)\\(\\s*(['"\`])([^'"\`]+)\\2\\s*,?([^\\n]*)`, 'i');
  for (const line of lines) {
    const m = line.match(re);
    if (!m) continue;
    const method = m[1].toUpperCase();
    const routePath = m[3];
    const rest = m[4] || '';
    const perm = (rest.match(/checkPermission\(\s*['"]([^'"]+)['"]\s*\)/) || [])[1] || routerPerm;
    const admin = /requireAdmin/.test(rest) || routerAdmin;
    out.push({ method, path: routePath, perm, admin });
  }
  return out;
}

const routeFiles = fs.readdirSync(path.join(ROOT, 'routes')).filter(f => f.endsWith('.js')).sort();
const all = [];
for (const f of routeFiles) {
  const src = fs.readFileSync(path.join(ROOT, 'routes', f), 'utf8');
  const required = [...src.matchAll(/require\(['"]\.\.\/controllers\/(\w+)['"]\)/g)].map(x => x[1]);
  const base = mounts.get(f.replace(/\.js$/, '')) || `(unmounted:${f})`;
  for (const r of parseRouteFile(path.join(ROOT, 'routes', f))) {
    all.push({ ...r, file: f, base, handlers: required });
  }
}

function fullPath(base, p) {
  if (p === '/') return base;
  return base + p;
}

const rows = [
  ...all.map(r => ({ ...r, full: fullPath(r.base, r.path) })),
  ...directRoutes.map(r => ({ ...r, full: r.path, file: r.source, base: '', handlers: [] })),
];

// ── Markdown ────────────────────────────────────────────────────────────────
const byMount = new Map();
for (const r of rows) {
  const key = r.full.split('/').slice(0, 3).join('/'); // /api/<segment>
  if (!byMount.has(key)) byMount.set(key, []);
  byMount.get(key).push(r);
}

let md = '';
md += '# Route Inventory (generated)\n\n';
md += '> Generated by `node scripts/gen_route_inventory.js` from `app.js` + `routes/*.js`.\n';
md += '> Every route below is behind the global `requireAuth` guard unless its mount is `/api/auth`.\n';
md += '> `req.branchId` is attached by `middleware/branchScope.js` for every authenticated request.\n\n';
md += `Total routes: **${rows.length}** across **${routeFiles.length}** route files.\n\n`;

for (const [mount, list] of [...byMount.entries()].sort()) {
  md += `## \`${mount}\`\n\n`;
  md += '| Method | Path | Permission gate | Admin only | Source |\n|---|---|---|---|---|\n';
  for (const r of list.sort((a, b) => a.full.localeCompare(b.full) || a.method.localeCompare(b.method))) {
    md += `| \`${r.method}\` | \`${r.full}\` | ${r.perm ? '`' + r.perm + '`' : '—'} | ${r.admin ? 'yes' : '—'} | ${r.file} |\n`;
  }
  md += '\n';
}

// ── README comparison ───────────────────────────────────────────────────────
const readmePath = path.join(ROOT, 'readme.md');
if (fs.existsSync(readmePath)) {
  const readme = fs.readFileSync(readmePath, 'utf8');
  const documented = new Set();
  for (const m of readme.matchAll(/\|\s*`(GET|POST|PUT|PATCH|DELETE)`\s*\|\s*`([^`]+)`/g)) {
    documented.add(`${m[1]} ${m[2].split('?')[0]}`);
  }
  const actual = new Set(rows.map(r => `${r.method} ${r.full}`));
  const undocumented = [...actual].filter(x => !documented.has(x)).sort();
  const phantom = [...documented].filter(x => !actual.has(x)).sort();

  md += '## Diff vs README route tables\n\n';
  md += `README documents **${documented.size}** routes; code exposes **${actual.size}**.\n\n`;
  md += '### Implemented but NOT documented in README\n\n';
  if (undocumented.length === 0) md += '_none_\n';
  for (const u of undocumented) md += `- \`${u}\`\n`;
  md += '\n### Documented in README but NOT implemented\n\n';
  if (phantom.length === 0) md += '_none_\n';
  for (const p of phantom) md += `- \`${p}\`\n`;
  md += '\n';
}

// ── Frontend pages ──────────────────────────────────────────────────────────
const publicDir = path.join(ROOT, 'public');
const pages = fs.readdirSync(publicDir).filter(f => f.endsWith('.html')).sort();
md += '## Frontend pages (`public/*.html`)\n\n';
md += `Actual page count: **${pages.length}** (README claims 18).\n\n`;
for (const p of pages) md += `- \`${p}\`\n`;
md += '\n';

process.stdout.write(md);
